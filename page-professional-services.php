   <h2>
    Private Services (Fee for Service)
   </h2>
   <p class="ps-eyebrow">
    Province-wide • Online and in-person, subject to availability
   </p>
   <p>
    Private, fee-for-service supports for Autistic individuals or those with other neurodevelopmental differences of any age. Using a neuroaffirming, person-centred approach, our team helps with practical goals and everyday skills. Virtual supports can be offered across Alberta.
   </p>
   <p>
    <strong>
     Support may include:
    </strong>
   </p>
   <ul>
    <li>
     Emotional or behavioural regulation, such as relaxation and stress management
    </li>
    <li>
     Motor skills, including climbing, jumping, and writing
    </li>
    <li>
     Communication and understanding information
    </li>
    <li>
     Activities of daily living, such as eating and dressing
    </li>
    <li>
     Executive functioning, such as planning, organizing, and time management
    </li>
   </ul>
   <p>
    The team develops an individualized plan around your goals and priorities. Supports may be offered at home, in the community, other meaningful settings, or virtually.
